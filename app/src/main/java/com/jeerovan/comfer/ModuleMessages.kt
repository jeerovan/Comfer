private val numberedModuleMessages = listOf(
    Regex("On-device dictation stopped \\(error ([0-9]+)\\). Reopen dictation and try Use device speech provider.") to R.string.module_dictation_device_error,
    Regex("The device speech provider could not complete dictation \\(error ([0-9]+)\\). Check its settings and try again.") to R.string.module_dictation_provider_error,
    Regex("Speech recognition stopped \\(provider error ([0-9]+)\\)") to R.string.module_dictation_error,
)

internal fun localizedModuleMessage(resources: Resources, message: String?): String {
    moduleMessageResources[message]?.let { return resources.getString(it) }
    if (message != null) {
        numberedModuleMessages.forEach { (pattern, resource) ->
            pattern.matchEntire(message)?.groupValues?.get(1)?.toIntOrNull()?.let {
                return resources.getString(resource, it)
            }
        }
        // Activity callbacks can already carry a localized, app-owned message.
        moduleMessageResources.values.forEach {
            if (resources.getString(it) == message) return message
        }
    }
    return resources.getString(R.string.module_could_not_complete_this_action_please_try_again)
}
